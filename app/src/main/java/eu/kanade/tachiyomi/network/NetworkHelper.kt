package eu.kanade.tachiyomi.network

import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import okhttp3.Interceptor
import okhttp3.Response
import okhttp3.OkHttpClient
import android.content.Context
import java.util.concurrent.TimeUnit
import eu.kanade.tachiyomi.network.interceptor.CloudflareInterceptor
import okhttp3.logging.HttpLoggingInterceptor
import okhttp3.HttpUrl.Companion.toHttpUrl
import okhttp3.dnsoverhttps.DnsOverHttps
import java.net.InetAddress

/**
 * Network helper responsible for providing OkHttpClient instances.
 * Many Tachiyomi/Mihon extensions (like Madara-based ones) depend on this.
 */
class NetworkHelper(context: Context) {

    /**
     * Shared cookie jar that persists to SharedPreferences.
     */
    val cookieJar = AndroidCookieJar(context)

    /**
     * Shared interceptor for updating User-Agent.
     */
    val userAgentInterceptor = UserAgentInterceptor()

    /**
     * Interceptor to bypass Cloudflare blank pages.
     */
    val cloudflareInterceptor = CloudflareInterceptor(context, cookieJar)

    /**
     * Standard client for general requests.
     */
    val client: OkHttpClient by lazy {
        val logging = HttpLoggingInterceptor().apply {
            level = HttpLoggingInterceptor.Level.BASIC
        }

        val cookieInterceptor = Interceptor { chain ->
            val originalRequest = chain.request()
            val url = originalRequest.url.toString()
            // Grab the cookies the user generated by using the WebView
            val cookies = android.webkit.CookieManager.getInstance().getCookie(url)
            
            val newRequest = if (!cookies.isNullOrEmpty()) {
                originalRequest.newBuilder()
                    .header("Cookie", cookies)
                    .build()
            } else {
                originalRequest
            }
            chain.proceed(newRequest)
        }

        // 1. Create a bootstrap client for the DNS lookups
        val bootstrapClient = OkHttpClient.Builder().build()

        // 2. Build the Cloudflare DoH tunnel
        val dns = DnsOverHttps.Builder().client(bootstrapClient)
            .url("https://cloudflare-dns.com/dns-query".toHttpUrl())
            .bootstrapDnsHosts(
                InetAddress.getByName("1.1.1.1"),
                InetAddress.getByName("1.0.0.1"),
                InetAddress.getByName("2606:4700:4700::1111"),
                InetAddress.getByName("2606:4700:4700::1001")
            )
            .build()

        // 3. Attach it to your main client with padded VPN timeouts
        OkHttpClient.Builder()
            .dns(dns) // Bypasses VPN DNS hijacking
            .connectTimeout(30, TimeUnit.SECONDS) // Padded for VPN latency
            .readTimeout(30, TimeUnit.SECONDS)
            .writeTimeout(30, TimeUnit.SECONDS)
            .addInterceptor { chain ->
                // Hardcoded User-Agent to bypass CDN bot-checks on VPN IPs
                val request = chain.request().newBuilder()
                    .header("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")
                    .build()
                chain.proceed(request)
            }
            .addInterceptor(cookieInterceptor)
            .addInterceptor(logging)
            .cookieJar(cookieJar)
            .addNetworkInterceptor { chain ->
                // Simple Rate Limiter: throttle outgoing image/chapter requests to prevent HTTP 429
                Thread.sleep(250)
                chain.proceed(chain.request())
            }
            .addInterceptor(cloudflareInterceptor)
            .build()
    }

    /**
     * Specialized client for bypassing Cloudflare or specific anti-bot protections.
     */
    val cloudflareClient: OkHttpClient by lazy {
        client.newBuilder()
            .build()
    }
}

class SequentialInterceptor : Interceptor {
    private val mutex = Mutex()

    override fun intercept(chain: Interceptor.Chain): Response {
        // runBlocking is required here because interceptors are synchronous,
        // but Mutex allows us to safely queue the threads without blocking the CPU.
        return runBlocking {
            mutex.withLock {
                chain.proceed(chain.request())
            }
        }
    }
}
